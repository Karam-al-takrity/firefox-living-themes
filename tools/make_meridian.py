def url(body):
    svg = (f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16' fill='none' stroke='{BRASS}' "
           f"stroke-width='1.2' stroke-linecap='round' stroke-linejoin='round'>{body}</svg>").replace('"', "'")
    return "data:image/svg+xml," + quote(svg, safe="/:=' ,.-")


